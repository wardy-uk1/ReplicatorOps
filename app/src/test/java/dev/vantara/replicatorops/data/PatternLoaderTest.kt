package dev.vantara.replicatorops.data

import org.junit.Assert.assertEquals
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class PatternLoaderTest {
    @get:Rule val tmp = TemporaryFolder()

    private fun zip(name: String, vararg entries: String, gcodeHeader: String = "; generated by QIDIStudio 02.04.00\n"): File {
        val f = tmp.newFile(name)
        ZipOutputStream(f.outputStream()).use { z ->
            entries.forEach { e ->
                z.putNextEntry(ZipEntry(e))
                z.write((if (e.endsWith(".gcode")) gcodeHeader else "x").toByteArray())
                z.closeEntry()
            }
        }
        return f
    }

    @Test fun gcodeIsSliced() {
        assertEquals(PatternKind.SLICED, PatternLoader.classify(tmp.newFile("benchy.gcode")))
    }

    @Test fun slicedThreeMf() {
        val f = zip("gargoyles.gcode.3mf", "3D/3dmodel.model", "Metadata/plate_1.gcode", "Metadata/plate_1.png")
        assertEquals(PatternKind.SLICED, PatternLoader.classify(f))
    }

    @Test fun unslicedThreeMfAndStlNeedSlicing() {
        val f = zip("model.3mf", "3D/3dmodel.model", "Metadata/model_settings.config")
        assertEquals(PatternKind.NEEDS_SLICING, PatternLoader.classify(f))
        assertEquals(PatternKind.NEEDS_SLICING, PatternLoader.classify(tmp.newFile("part.STL")))
    }

    @Test fun otherFilesUnsupported() {
        assertEquals(PatternKind.UNSUPPORTED, PatternLoader.classify(tmp.newFile("photo.jpg")))
    }

    @Test fun safeNames() {
        assertEquals("a_b_c.gcode", PatternLoader.safeName("a/b:c.gcode"))
    }

    @Test fun originsAreDetected() {
        assertEquals(PatternOrigin.PRUSA, PatternLoader.origin(zip("ghost.3mf", "3D/3dmodel.model", "Metadata/Slic3r_PE.config")))
        assertEquals(PatternOrigin.BAMBU, PatternLoader.origin(zip("mw.3mf", "3D/3dmodel.model", "Metadata/project_settings.config")))
        assertEquals(PatternOrigin.PLAIN_MODEL, PatternLoader.origin(tmp.newFile("x.stl")))
    }

    @Test fun bambuSlicedIsRefused() {
        val f = zip("makerworld.gcode.3mf", "Metadata/plate_1.gcode", gcodeHeader = "; HEADER_BLOCK_START\n; generated by BambuStudio 02.03.00.70\n")
        assertEquals(PatternKind.WRONG_PRINTER, PatternLoader.classify(f))
        val g = tmp.newFile("bambu.gcode").apply { writeText("; generated by BambuStudio 02.03\nG28\n") }
        assertEquals(PatternKind.WRONG_PRINTER, PatternLoader.classify(g))
        val q = tmp.newFile("qidi.gcode").apply { writeText("; generated by QIDIStudio 02.04\nG28\n") }
        assertEquals(PatternKind.SLICED, PatternLoader.classify(q))
    }

    @Test fun plainGcodeNamedThreeMfIsSliced() {
        // Files retrieved from a QIDI printer can be plain G-code that keeps the .gcode.3mf name.
        val f = tmp.newFile("Organizer (1).gcode.3mf")
        f.writeText("; HEADER_BLOCK_START\n; generated by QIDIStudio 02.04.00\n; HEADER_BLOCK_END\nG28\nM104 S220\nG1 X10 Y10\n")
        assertEquals(PatternKind.SLICED, PatternLoader.classify(f))
    }

    @Test fun textThatIsNotGcodeNeedsSlicing() {
        val f = tmp.newFile("notes.3mf")
        f.writeText("hello there, this is not a print file\n")
        assertEquals(PatternKind.NEEDS_SLICING, PatternLoader.classify(f))
    }
}
